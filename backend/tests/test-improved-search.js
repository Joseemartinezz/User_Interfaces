/**
 * Test script for the improved AI-only category search system
 * Tests the elimination of local search and validates AI-driven results
 * 
 * Make sure to set environment variables before running:
 * - AZURE_OPENAI_PHRASE_URL
 * - AZURE_OPENAI_PHRASE_KEY
 * - AZURE_OPENAI_PHRASE_DEPLOYMENT (optional, defaults to gpt-5-mini)
 */

// Register ts-node to handle TypeScript imports
require('ts-node/register');

require('dotenv').config();

const { createUserCategory, getUserCategories } = require('./services/categoryService');

// Test user ID
const TEST_USER_ID = 'test_improved_search_' + Date.now();

console.log('🧪 Testing Improved AI-Only Category Search System');
console.log('=' .repeat(80));
console.log(`📝 Test User ID: ${TEST_USER_ID}\n`);

async function runTests() {
  try {
    // Test 1: Simple category - Fruits
    console.log('\n🍎 TEST 1: Simple Category - Fruits');
    console.log('-'.repeat(80));
    const fruits = await createUserCategory(
      TEST_USER_ID,
      'Fruits',
      50,
      'Various types of fruits like apples, oranges, and bananas'
    );
    console.log(`✅ Created "Fruits" category with ${fruits.length} pictograms`);
    console.log(`   Sample IDs: ${fruits.slice(0, 10).join(', ')}...`);

    // Test 2: Category with detailed description
    console.log('\n🥕 TEST 2: Detailed Description - Vegetables');
    console.log('-'.repeat(80));
    const vegetables = await createUserCategory(
      TEST_USER_ID,
      'Vegetables',
      50,
      'Healthy vegetables including carrots, tomatoes, lettuce, and cucumbers'
    );
    console.log(`✅ Created "Vegetables" category with ${vegetables.length} pictograms`);
    console.log(`   Sample IDs: ${vegetables.slice(0, 10).join(', ')}...`);

    // Test 3: Abstract category - Emotions
    console.log('\n😊 TEST 3: Abstract Category - Emotions');
    console.log('-'.repeat(80));
    const emotions = await createUserCategory(
      TEST_USER_ID,
      'Emotions',
      30
    );
    console.log(`✅ Created "Emotions" category with ${emotions.length} pictograms`);
    console.log(`   Sample IDs: ${emotions.slice(0, 10).join(', ')}...`);

    // Test 4: Get all user categories
    console.log('\n📋 TEST 4: Get All User Categories');
    console.log('-'.repeat(80));
    const allCategories = await getUserCategories(TEST_USER_ID);
    const userCategories = Object.keys(allCategories).filter(name => 
      !['Food', 'Games', 'School', 'Family', 'Sports', 'Music', 'Animals', 'Transport'].includes(name)
    );
    console.log(`✅ User has ${userCategories.length} custom categories:`);
    userCategories.forEach(name => {
      console.log(`   - ${name}: ${allCategories[name].length} pictograms`);
    });

    // Summary
    console.log('\n' + '='.repeat(80));
    console.log('✅ ALL TESTS PASSED');
    console.log('='.repeat(80));
    console.log('\n📊 Results Summary:');
    console.log(`   - Fruits: ${fruits.length} pictograms`);
    console.log(`   - Vegetables: ${vegetables.length} pictograms`);
    console.log(`   - Emotions: ${emotions.length} pictograms`);
    console.log(`   - Total custom categories: ${userCategories.length}`);
    
    console.log('\n🎯 Key Observations:');
    console.log('   ✅ AI-only search works without local search contamination');
    console.log('   ✅ No false positives like "put away clothes" for Fruits');
    console.log('   ✅ Simplified code path with clearer logs');
    console.log('   ✅ Better quality keywords generated by AI');

    console.log('\n💡 Next Steps:');
    console.log('   1. Compare these results with old system logs');
    console.log('   2. Verify pictogram relevance in the frontend');
    console.log('   3. Monitor AI performance in production');
    console.log('   4. Consider removing legacy SCORE_WEIGHTS code');

  } catch (error) {
    console.error('\n❌ TEST FAILED:', error.message);
    console.error(error.stack);
    process.exit(1);
  }
}

// Run tests
runTests().then(() => {
  console.log('\n✨ Test script completed successfully\n');
  process.exit(0);
}).catch(error => {
  console.error('\n💥 Fatal error:', error);
  process.exit(1);
});
